use super::*;
use crate::{FEA, SOLVED};
use cad_analysis::TESSELLATION;

fn near(a: f64, b: f64, t: f64) {
    assert!((a - b).abs() <= t, "{a} vs {b}");
}

fn bench(reference: f64, result: f64, tolerance: f64) -> Benchmark {
    Benchmark { case: CANTILEVER, quantity: "q", formula: "f", reference, result, tolerance, mesh: String::new(), computed: Accuracy::Approximate(FEA) }
}

#[test]
fn benchmark_rows() {
    let rows = benchmarks().unwrap();
    assert_eq!(rows.len(), 15);
    let cases: Vec<&str> = rows.iter().map(|b| b.case).collect();
    let mut want = vec![CANTILEVER; 6];
    want.extend([TENSION_BAR; 2]);
    want.extend([SOLID_BOX; 3]);
    want.extend([SOLID_CYLINDER; 3]);
    want.push(FOUR_BAR);
    assert_eq!(cases, want);
    for row in &rows {
        assert!(row.passed(), "{} {}: {}", row.case, row.quantity, row.error());
        assert_eq!(row.accuracy(), Accuracy::Validated(row.case));
    }
    let tip = [0.187285256165, 0.189825455235, 0.190406091856];
    let tip_err = [-0.024362, -0.011130, -0.008105];
    let stress = [30.743092366090, 30.260286324752, 30.064338474298];
    let stress_err = [0.024770, 0.008676, 0.002145];
    let meshes = ["h=10 mm: 189 nodes, 60 elements, 540 unknowns", "h=5 mm: 1025 nodes, 480 elements, 3000 unknowns", "h=2.5 mm: 6561 nodes, 3840 elements, 19440 unknowns"];
    for k in 0..3 {
        near(rows[2 * k].reference, 0.19196190476190476, 1e-14);
        near(rows[2 * k].result, tip[k], 1e-8);
        near(rows[2 * k].error(), tip_err[k], 1e-5);
        near(rows[2 * k + 1].reference, 30.0, 1e-12);
        near(rows[2 * k + 1].result, stress[k], 1e-8);
        near(rows[2 * k + 1].error(), stress_err[k], 1e-5);
        for row in &rows[2 * k..2 * k + 2] {
            assert_eq!(row.mesh, meshes[k]);
            assert_eq!(row.computed, Accuracy::Approximate(FEA));
        }
    }
    for i in [0, 1, 2, 3] {
        assert!(rows[i].error().abs() > rows[i + 2].error().abs(), "row {i} does not converge");
    }
    near(rows[6].reference, 1.0 / 210.0, 1e-15);
    near(rows[6].result, 0.004761904761904762, 1e-11);
    near(rows[7].reference, 10.0, 1e-12);
    near(rows[7].result, 10.0, 1e-9);
    assert_eq!(rows[6].mesh, "h=5 mm: 1025 nodes, 480 elements, 3000 unknowns");
    assert_eq!(rows[7].mesh, "h=5 mm: 1025 nodes, 480 elements, 3000 unknowns");
    for (row, want) in rows[8..11].iter().zip([10000.0, 166.66666666666666, 8416.666666666666]) {
        near(row.result, want, 1e-9);
        assert_eq!(row.computed, Accuracy::Exact);
        assert_eq!(row.mesh, "12 triangles");
    }
    let refs = [6283.185307179586, 366.5191429188092, 314.1592653589793];
    let results = [6266.661678215216, 365.1434770701055, 312.50950892586326];
    let errs = [-0.002630, -0.003753, -0.005251];
    for (k, row) in rows[11..14].iter().enumerate() {
        near(row.reference, refs[k], 1e-9);
        near(row.result, results[k], 1e-9);
        near(row.error(), errs[k], 1e-5);
        assert_eq!(row.computed, Accuracy::Approximate(TESSELLATION));
        assert_eq!(row.mesh, "196 triangles");
    }
    let bar = &rows[14];
    assert_eq!(bar.reference, 0.0);
    assert!(0.0 <= bar.result && bar.result <= 1e-6);
    assert_eq!(bar.computed, Accuracy::Approximate(SOLVED));
    assert_eq!(bar.mesh, "36 steps of 10°");
}

#[test]
fn error_and_label() {
    let b = bench(2.0, 2.1, 0.03);
    near(b.error(), 0.05, 1e-12);
    assert!(!b.passed());
    assert_eq!(b.accuracy().to_string(), "approximate (FEA, linear elastic)");
    let b = bench(2.0, 2.05, 0.03);
    assert!(b.passed());
    assert_eq!(b.accuracy().to_string(), "validated against cantilever beam");
    let b = bench(0.0, -3e-7, 1e-6);
    assert_eq!(b.error(), -3e-7);
    assert!(b.passed());
    assert!(!bench(2.0, f64::NAN, 0.03).passed());
}

#[test]
fn markdown_report() {
    let t = validation_markdown(&[bench(2.0, 2.05, 0.03), bench(0.0, -3e-7, 1e-6)], "Date: x");
    assert!(t.starts_with("# Validation report\n\nGenerated by `cargo run --release -p cad-bench -- validate`"));
    assert!(t.contains("\nDate: x\n"));
    assert!(t.contains("| Case | Quantity | Reference formula | Reference | Result | Error | Tolerance | Pass | Mesh | Label |\n|---|---|---|---|---|---|---|---|---|---|\n"));
    assert!(t.contains("| cantilever beam | q | f | 2.000000000 | 2.050000000 | +2.50e-2 | 3e-2 | yes |  | validated against cantilever beam |\n"));
    assert!(t.contains("| cantilever beam | q | f | 0.000000000 | -0.000000300 | -3.00e-7 | 1e-6 | yes |"));
    assert_eq!(t.lines().filter(|l| l.starts_with("| cantilever beam |")).count(), 2);
    assert!(t.ends_with(NOTES));
    assert!(!NOTES.contains('|') && !INTRO.contains('|'));
}
